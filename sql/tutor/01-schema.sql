-- 6. t_application 申请表(老师投递记录)
-- 业务用途:老师向需求单投递的申请记录,家长选老师的数据源
-- 关键规则(状态机):
--   · 0 申请中 → 1 被选中(家长选中,同时生成订单)
--   · 0 → 2 已撤回(家长未选前可撤回,终态,不可重投该需求)
--   · 1 → 3 已排除(老师反悔,家长不可再选他)
--   · 0 → 5 已失效(需求编辑后重开,原申请清空;失效行可重新投递新行)
--   · 4 已试课未通过 → 1 可再选(同行走状态流转,不产生新行)
--   · 部分唯一索引:同一老师对同一需求仅一行活跃申请(除 5 已失效外)
--   · 简历隐藏期间,其 status=0 的申请在家长端查询时排除(展示层规则,状态不变)
-- 关联:t_demand 1 ── 0..n;t_order 1 ── 0..n(试课失败后再选产生新订单)
-- ============================================================
CREATE TABLE t_application (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, -- 主键,自增
    demand_id     BIGINT    NOT NULL,                                  -- 目标需求(关联 t_demand.id)
    tutor_user_id BIGINT    NOT NULL,                                  -- 投递老师(关联 t_user.id)
    status        SMALLINT  NOT NULL DEFAULT 0,                        -- 状态:0 申请中 / 1 被选中 / 2 已撤回(终态) / 3 已排除(反悔) / 4 已试课未通过(可再选) / 5 已失效
    apply_at      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,        -- 投递时间
    updated_at    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP         -- 更新时间
);
CREATE INDEX idx_t_application_demand      ON t_application (demand_id, status);     -- 家长端申请列表
CREATE INDEX idx_t_application_tutor       ON t_application (tutor_user_id, status); -- 老师端我的申请
-- 同一老师对同一需求仅一行(撤回=终态不可重投;试课失败可再选走同行走状态流转;仅"5 已失效"不占位,允许重新投递)
CREATE UNIQUE INDEX uk_t_application_demand_tutor ON t_application (demand_id, tutor_user_id) WHERE status IN (0, 1, 2, 3, 4);

COMMENT ON TABLE  t_application              IS '老师投递记录(申请);家长选老师的数据源';
COMMENT ON COLUMN t_application.demand_id      IS '目标需求(关联 t_demand.id)';
COMMENT ON COLUMN t_application.tutor_user_id  IS '投递老师(关联 t_user.id)';
COMMENT ON COLUMN t_application.status         IS '0 申请中 / 1 被选中 / 2 已撤回(终态,不可重投该需求)/ 3 已排除(反悔)/ 4 已试课未通过(可再选)/ 5 已失效(需求编辑重上架清空,可重新投递)';
COMMENT ON COLUMN t_application.apply_at       IS '投递时间';
COMMENT ON COLUMN t_application.updated_at     IS '更新时间';

