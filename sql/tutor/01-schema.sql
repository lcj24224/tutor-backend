COMMENT ON COLUMN t_parent_profile.publish_enabled IS '发布需求权:加客服微信+朋友圈判断后人工开通';
COMMENT ON COLUMN t_parent_profile.wechat_confirmed IS '是否已确认加客服微信';
COMMENT ON COLUMN t_parent_profile.report_count    IS '举报核实次数(核实成立强制下架其全部需求,不连坐老师身份)';
COMMENT ON COLUMN t_parent_profile.audit_note      IS '客服审核备注(对用户不可见)';
COMMENT ON COLUMN t_parent_profile.created_at      IS '创建时间';
COMMENT ON COLUMN t_parent_profile.updated_at      IS '更新时间';

-- ============================================================
-- 5. t_demand 需求表(家长可发多个)
-- 业务用途:家长发布的家教需求单,需求广场数据源
-- 关键规则:
--   · status 状态机:0 接收申请中(可见可申请)/ 1 已选定老师(不接受新申请)/ 2 已关闭(完成/失败/超时/家长手动下架/举报核实/家长放弃);2→0 可重开
--   · 可见性:status=0 且 review_status=1 才对外可见可申请
--   · 敏感字段(科目/年级/地址/时薪)编辑 → review_status 回 0 且强制不可见,审核通过恢复
--   · 非敏感字段编辑走敏感词检测,不重审
--   · 重开规则:对比 edit_version 判定"编辑过"——编辑过 → 原申请置 5 失效;未编辑 → 原申请保留
--   · 地址前台脱敏(仅到区);详细地址与坐标仅客服后台可见
--   · 家长活跃需求上限:同时"接收申请中"最多 3 个(应用层控制)
-- 关联:t_user(parent_user_id);t_application 1 ── 0..n;t_order 1 ── 0..n
-- ============================================================
CREATE TABLE t_demand (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, -- 主键,自增
    parent_user_id   BIGINT       NOT NULL,                          -- 发布家长(关联 t_user.id)
    subjects         JSONB        NOT NULL DEFAULT '[]'::jsonb,      -- 授课科目数组(字典 subject,敏感字段)
    grade            VARCHAR(32)  NOT NULL,                          -- 学段枚举(字典 grade,敏感字段)
    hourly_min       DECIMAL(6,1),                                   -- 期望时薪下限(元/小时,敏感字段)
    hourly_max       DECIMAL(6,1),                                   -- 期望时薪上限(元/小时,敏感字段)
    tutor_gender_req SMALLINT     NOT NULL DEFAULT 0,                -- 性别要求:0 不限 / 1 男 / 2 女
    tutor_edu_req    VARCHAR(32),                                    -- 学历要求枚举(字典 education,空=不限)
    city             VARCHAR(32)  NOT NULL,                          -- 城市(敏感字段)
    district         VARCHAR(32)  NOT NULL,                          -- 区(前台展示仅到区)
    address_detail   VARCHAR(255) NOT NULL,                          -- 详细地址到小区/街道(前台脱敏不展示,敏感字段)
    address_lat      DECIMAL(10,6),                                  -- 地址纬度(geocoder 转坐标,前台不可见,仅距离计算用)
    address_lng      DECIMAL(10,6),                                  -- 地址经度(同上)
    teach_time_req   JSONB,                                          -- 授课时间要求(结构化,同简历 teach_time 格式)
    student_info     TEXT,                                           -- 学生情况(非敏感)
    remark           TEXT,                                           -- 备注/其他要求(非敏感,自由文本,不入筛选)
    status           SMALLINT     NOT NULL DEFAULT 0,                -- 状态:0 接收申请中 / 1 已选定老师 / 2 已关闭
    review_status    SMALLINT     NOT NULL DEFAULT 0,                -- 审核状态:0 待审核 / 1 通过 / 2 拒绝(敏感字段编辑→回 0 且强制不可见)
    review_reason    VARCHAR(255),                                   -- 审核意见
