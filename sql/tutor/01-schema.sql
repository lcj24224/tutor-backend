-- ============================================================
-- 1. t_user 用户表
-- 业务用途:微信登录用户的账号主表,完整手机号唯一落点(AES 加密)
-- 关键规则:
--   · openid 为登录凭证,唯一
--   · mobile_hash 仅客服后台按手机号等值查找用(统一盐 SHA-256,不可逆)
--   · 身份规则:本表无身份字段;老师身份 = t_tutor_profile.cert_status=2,
--     家长身份 = t_parent_profile.publish_enabled=true,游客 = 两者皆无;三种身份可并存
--   · status=1 封禁为用户级处罚,两端全封
-- 关联:1 ── 0..1 t_tutor_profile;1 ── 0..1 t_parent_profile
-- ============================================================
CREATE TABLE t_user (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, -- 主键,自增
    openid           VARCHAR(64)  NOT NULL,                              -- 微信 openid,登录凭证(唯一)
    unionid          VARCHAR(64),                                        -- 微信 unionid(预留,暂无公众号,可空)
    nickname         VARCHAR(64),                                        -- 微信昵称
    avatar_url       VARCHAR(512),                                       -- 微信头像 URL
    mobile_encrypted VARCHAR(256),                                       -- AES 加密手机号(注册/首次发布时必填;解密仅后台接口有权)
    mobile_hash      VARCHAR(64),                                        -- 手机号统一盐 SHA-256 哈希(盐在环境变量),仅客服后台等值查找,不可逆
    last_city        VARCHAR(32),                                        -- 最后定位城市(仅用于首页默认城市)
    status           SMALLINT     NOT NULL DEFAULT 0,                    -- 0 正常 / 1 封禁(用户级,两端全封)
    created_at       TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,    -- 创建时间
    updated_at       TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP     -- 更新时间
);
CREATE UNIQUE INDEX uk_t_user_openid      ON t_user (openid);        -- 登录凭证唯一
CREATE INDEX        idx_t_user_mobile_hash ON t_user (mobile_hash);  -- 客服按手机号哈希查找

COMMENT ON TABLE  t_user               IS '用户表(微信登录,完整手机号唯一落点,AES 加密)';
COMMENT ON COLUMN t_user.id               IS '主键,自增';
COMMENT ON COLUMN t_user.openid           IS '微信 openid,登录凭证,唯一';
COMMENT ON COLUMN t_user.unionid          IS '微信 unionid,预留(暂无公众号)';
COMMENT ON COLUMN t_user.nickname         IS '微信昵称';
COMMENT ON COLUMN t_user.avatar_url       IS '微信头像 URL';
COMMENT ON COLUMN t_user.mobile_encrypted IS 'AES 加密手机号,解密仅后台接口有权';
COMMENT ON COLUMN t_user.mobile_hash      IS '手机号统一盐 SHA-256 哈希,仅用于客服后台按手机号等值查找,不可逆';
COMMENT ON COLUMN t_user.last_city        IS '最后定位城市(仅用于首页默认城市)';
COMMENT ON COLUMN t_user.status           IS '0 正常 / 1 封禁(用户级处罚,两端全封)';
COMMENT ON COLUMN t_user.created_at       IS '创建时间';
COMMENT ON COLUMN t_user.updated_at       IS '更新时间';

-- ============================================================
-- 2. t_tutor_profile 老师身份表(每老师一行)
-- 业务用途:老师身份的认证状态、反悔与举报计数、强制下线
-- 关键规则:
--   · cert_status=2(已通过)才拥有老师身份:可看需求广场/投递/简历可见
--   · 认证材料:学生证照片 + 学信网截图(个人照片已取消,头像选填在简历表)
--   · 反悔次数满 3 → 自动 blacklist=true(禁投递、简历强制隐藏)
--   · 身份级处罚不连坐:blacklist 不影响该用户的家长身份
--   · 申诉恢复:blacklist=false + 计数清零,历史保留在 t_break_promise_log
-- 关联:t_user 1 ── 0..1;t_tutor_resume 1 ── 1
-- ============================================================
CREATE TABLE t_tutor_profile (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, -- 主键,自增
    user_id              BIGINT       NOT NULL,                          -- 关联 t_user.id(唯一,一人一行)
    cert_status          SMALLINT     NOT NULL DEFAULT 0,                -- 认证状态:0 未提交 / 1 待审核 / 2 已通过 / 3 已拒绝
    cert_student_card    VARCHAR(512),                                   -- 学生证照片 URL
    cert_xuexin          VARCHAR(512),                                   -- 学信网截图 URL
    cert_reject_reason   VARCHAR(255),                                   -- 拒绝原因(老师可见,可修改材料后重提)
    cert_audit_at        TIMESTAMP,                                      -- 最近一次认证审核时间
    break_promise_count  INT          NOT NULL DEFAULT 0,                -- 反悔次数(被选中后拒绝),满 3 触发 blacklist=true
    report_count         INT          NOT NULL DEFAULT 0,                -- 举报核实次数(排序隐藏权重;核实成立强制隐藏简历)
    blacklist            BOOLEAN      NOT NULL DEFAULT false,            -- 强制下线开关:禁投递、简历强制隐藏
    blacklist_reason     VARCHAR(255),                                   -- 下线原因
    appeal_status        SMALLINT     NOT NULL DEFAULT 0,                -- 申诉状态:0 无申诉 / 1 申诉中 / 2 已恢复
    created_at           TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP, -- 创建时间
    updated_at           TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP  -- 更新时间
);
CREATE UNIQUE INDEX uk_t_tutor_profile_user ON t_tutor_profile (user_id);  -- 一人一身份行

COMMENT ON TABLE  t_tutor_profile              IS '老师身份表(认证状态+反悔+举报+下线);老师身份拥有 = cert_status=2';
COMMENT ON COLUMN t_tutor_profile.user_id        IS '关联 t_user.id,唯一(一人一行)';
COMMENT ON COLUMN t_tutor_profile.cert_status    IS '认证状态:0 未提交 / 1 待审核 / 2 已通过 / 3 已拒绝;通过前不可看需求广场/投递/简历可见';
COMMENT ON COLUMN t_tutor_profile.cert_student_card IS '学生证照片 URL';
COMMENT ON COLUMN t_tutor_profile.cert_xuexin    IS '学信网截图 URL';
COMMENT ON COLUMN t_tutor_profile.cert_reject_reason IS '拒绝原因(老师可见,可修改材料后重提)';
COMMENT ON COLUMN t_tutor_profile.cert_audit_at  IS '最近一次认证审核时间';
COMMENT ON COLUMN t_tutor_profile.break_promise_count IS '反悔次数(被选中后拒绝),满 3 触发 blacklist=true';
COMMENT ON COLUMN t_tutor_profile.report_count   IS '举报核实次数(排序隐藏权重;核实成立强制隐藏简历)';
COMMENT ON COLUMN t_tutor_profile.blacklist      IS '强制下线:禁投递、简历强制隐藏;申诉恢复后计数清零,历史在 t_break_promise_log';
COMMENT ON COLUMN t_tutor_profile.blacklist_reason IS '下线原因';
COMMENT ON COLUMN t_tutor_profile.appeal_status  IS '0 无申诉 / 1 申诉中 / 2 已恢复';
COMMENT ON COLUMN t_tutor_profile.created_at     IS '创建时间';
COMMENT ON COLUMN t_tutor_profile.updated_at     IS '更新时间';

-- ============================================================
-- 3. t_tutor_resume 简历表(一人一行,持续更新)
-- 业务用途:老师的家教简历,简历广场数据源
-- 关键规则:
--   · 实际可见 = visible AND review_status=1 AND profile.blacklist=false AND profile.cert_status=2
--   · 敏感字段(学校/学历/擅长学科)编辑 → review_status 回 0 且强制 visible=false,审核通过自动恢复可见
--   · 非敏感字段编辑不重审(走敏感词检测),可见性不受影响
--   · 隐藏期间存量申请在家长端查询时排除;已生成订单不受影响
--   · embedding 向量列先建不填充,二期批跑回填后启用语义检索
--   · 禁止字段:简历任何位置无微信号(个人介绍中出现的微信号由客服审核时删除)
-- 关联:t_tutor_profile 1 ── 1
-- ============================================================
CREATE TABLE t_tutor_resume (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, -- 主键,自增
    user_id       BIGINT       NOT NULL,                               -- 关联 t_user.id(唯一,一人一简历)
    name          VARCHAR(32)  NOT NULL,                               -- 姓名
    avatar_url    VARCHAR(512),                                        -- 头像(选填,微信头像能力 chooseAvatar 一键带入)
    gender        SMALLINT     NOT NULL,                               -- 性别:1 男 / 2 女
    school        VARCHAR(64)  NOT NULL,                               -- 学校(敏感字段,编辑触发重审)
    education     VARCHAR(32)  NOT NULL,                               -- 学历枚举(字典 education:college/bachelor/p211/p985/master/doctor)
    subjects      JSONB        NOT NULL DEFAULT '[]'::jsonb,           -- 擅长学科数组(字典 subject,敏感字段),如 ["math","physics"]
    teach_grades  JSONB        NOT NULL DEFAULT '[]'::jsonb,           -- 可授课年级数组(字典 grade),如 ["junior1","junior2"]
    experience    TEXT,                                                -- 家教经验(非敏感)
    teach_time    JSONB,                                               -- 可授课时间结构,如 [{"day":"周末","slots":["上午","下午"]}]
    teach_areas   JSONB        NOT NULL DEFAULT '[]'::jsonb,           -- 可授课区域数组,如 ["海淀区","朝阳区"]
    hourly_min    DECIMAL(6,1),                                        -- 期望时薪下限(元/小时)
    hourly_max    DECIMAL(6,1),                                        -- 期望时薪上限(元/小时)
    intro         TEXT,                                                -- 个人介绍(非敏感,人工审核删微信号)
    embedding     vector(1024),                                        -- 语义向量(先建列不填充,二期 embedding 批跑回填)
    visible       BOOLEAN      NOT NULL DEFAULT false,                 -- 可见性开关:true 可见;审核中/被拒/强制下线时系统强制 false(仅控制他人能否看到/申请,不涉及内容编辑)
    review_status SMALLINT     NOT NULL DEFAULT 0,                     -- 审核状态:0 待审核 / 1 通过 / 2 拒绝(敏感字段编辑→回 0 且强制隐藏)
    review_reason VARCHAR(255),                                        -- 审核意见
    created_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,     -- 创建时间
    updated_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP      -- 更新时间
);
CREATE UNIQUE INDEX uk_t_tutor_resume_user    ON t_tutor_resume (user_id);               -- 一人一简历
CREATE INDEX        idx_t_tutor_resume_shelf  ON t_tutor_resume (review_status, visible); -- 简历广场按审核+可见过滤
CREATE INDEX        idx_t_tutor_resume_edu    ON t_tutor_resume (education);             -- 按学历筛选
CREATE INDEX        gin_t_tutor_resume_subjects ON t_tutor_resume USING gin (subjects);  -- 按学科筛选(JSONB @>)
CREATE INDEX        gin_t_tutor_resume_areas  ON t_tutor_resume USING gin (teach_areas); -- 按区域筛选(JSONB @>)
-- 语义检索索引:数据积累、embedding 回填后启用
-- CREATE INDEX hnsw_t_tutor_resume_embedding ON t_tutor_resume USING hnsw (embedding vector_cosine_ops);

COMMENT ON TABLE  t_tutor_resume              IS '简历表(一人一简历,持续更新);简历广场数据源';
COMMENT ON COLUMN t_tutor_resume.user_id        IS '关联 t_user.id,唯一(一人一简历)';
COMMENT ON COLUMN t_tutor_resume.name           IS '姓名';
COMMENT ON COLUMN t_tutor_resume.avatar_url     IS '头像(选填,微信头像能力 chooseAvatar 实现)';
COMMENT ON COLUMN t_tutor_resume.gender         IS '1 男 / 2 女';
COMMENT ON COLUMN t_tutor_resume.school         IS '学校(敏感字段,编辑触发重审)';
COMMENT ON COLUMN t_tutor_resume.education      IS '学历枚举(字典 education)';
COMMENT ON COLUMN t_tutor_resume.subjects       IS '擅长学科数组(字典 subject,敏感字段,编辑触发重审)';
COMMENT ON COLUMN t_tutor_resume.teach_grades   IS '可授课年级数组(字典 grade)';
COMMENT ON COLUMN t_tutor_resume.experience     IS '家教经验(非敏感)';
COMMENT ON COLUMN t_tutor_resume.teach_time     IS '可授课时间结构,如 [{"day":"周末","slots":["上午","下午"]}]';
COMMENT ON COLUMN t_tutor_resume.teach_areas    IS '可授课区域数组';
COMMENT ON COLUMN t_tutor_resume.hourly_min     IS '期望时薪下限(元/小时)';
COMMENT ON COLUMN t_tutor_resume.hourly_max     IS '期望时薪上限(元/小时)';
COMMENT ON COLUMN t_tutor_resume.intro          IS '个人介绍(非敏感,人工审核删微信号)';
COMMENT ON COLUMN t_tutor_resume.embedding      IS '语义向量(1024 维),由 intro+subjects+experience 经 embedding API 生成,二期批跑回填';
COMMENT ON COLUMN t_tutor_resume.visible        IS '可见性开关:true 可见 / false 隐藏,仅控制他人能否看到/申请,不涉及内容编辑;隐藏期间存量申请在家长端查询时排除';
COMMENT ON COLUMN t_tutor_resume.review_status  IS '审核状态:0 待审核 / 1 通过 / 2 拒绝;敏感字段编辑 → 回 0 且强制隐藏,审核通过自动恢复可见';
COMMENT ON COLUMN t_tutor_resume.review_reason  IS '审核意见';
COMMENT ON COLUMN t_tutor_resume.created_at     IS '创建时间';
COMMENT ON COLUMN t_tutor_resume.updated_at     IS '更新时间';

