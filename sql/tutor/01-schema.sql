COMMENT ON COLUMN t_order.fee_refunded_at  IS '退费时间(试课失败/收费后取消)';
COMMENT ON COLUMN t_order.fail_blame       IS '失败责任方:1 老师问题 / 2 家长问题(客服与家长沟通后填写,审计追溯用)';
COMMENT ON COLUMN t_order.fail_reason      IS '试课失败原因(客服填)';
COMMENT ON COLUMN t_order.cancel_reason    IS '取消原因(老师反悔/家长放弃,客服填)';
