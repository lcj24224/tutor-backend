    publish_enabled  BOOLEAN      NOT NULL DEFAULT false,            -- 发布需求权(客服加微信+朋友圈判断后人工开通)
    wechat_confirmed BOOLEAN      NOT NULL DEFAULT false,            -- 是否已确认加客服微信
    report_count     INT          NOT NULL DEFAULT 0,                -- 举报核实次数(核实成立强制下架其全部需求)
    audit_note       VARCHAR(255),                                   -- 客服审核备注(对用户不可见)
