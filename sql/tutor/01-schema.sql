CREATE TABLE t_audit_log (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, -- 主键,自增
    target_type VARCHAR(16)  NOT NULL,                               -- 审核对象:tutor_cert / tutor_resume / parent_publish / evaluation / appeal / report / order
    target_id   BIGINT,                                              -- 目标 ID(对应对象表主键)
    action      SMALLINT     NOT NULL,                               -- 动作:1 通过 / 2 拒绝 / 3 隐藏 / 4 恢复 / 5 下线
    operator_id BIGINT,                                              -- 操作客服(关联 system_users.id,多客服可追溯)
    reason      VARCHAR(255),                                        -- 原因/备注
    created_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP      -- 操作时间
);
CREATE INDEX idx_t_audit_log_target ON t_audit_log (target_type, target_id);  -- 按对象查询审核历史

COMMENT ON TABLE  t_audit_log              IS '人工审核动作留痕(仅后台,多客服可追溯)';
COMMENT ON COLUMN t_audit_log.target_type    IS '审核对象:tutor_cert / tutor_resume / parent_publish / evaluation / appeal / report / order';
COMMENT ON COLUMN t_audit_log.target_id      IS '目标 ID(对应对象表主键)';
COMMENT ON COLUMN t_audit_log.action         IS '动作:1 通过 / 2 拒绝 / 3 隐藏 / 4 恢复 / 5 下线';
COMMENT ON COLUMN t_audit_log.operator_id    IS '操作客服(关联 system_users.id)';
COMMENT ON COLUMN t_audit_log.reason         IS '原因/备注';
COMMENT ON COLUMN t_audit_log.created_at     IS '操作时间';

