-- 7. t_order 订单表
-- 业务用途:订单全生命周期,信息费前置收费的载体,动态墙数据源
-- 关键规则(状态机,信息费前置):
--   0 待确认(家长已选,等老师确认;超 12 小时每日 8:00 定时任务提醒管理员催办,不自动取消)
--     ├─老师确认 → 1 待收费(双方加客服微信)
--     └─老师反悔 → 5 已取消(需求回退 0,application 置 3,break_promise_count+1)
--   1 待收费 ──客服收费+发放联系方式──→ 2 试课中(fee_status=1)
--   2 试课中 ──客服标记──→ 3 已完成(需求关闭)/ 4 试课失败(先退费,fee_status=2 强制)
--   任意收费前 ──家长放弃(管理端取消)──→ 5 已取消(需求关闭)
--   收费后家长放弃 → 管理端取消 + 退费 → 5 已取消(fee_status=2)
--   · 试课失败必填 fail_blame(1 老师问题 / 2 家长问题)+ fail_reason,审计追溯
--   · 试课失败后续:家长还要老师 → 需求回退 0;家长不要了 → 需求关闭 2
--   · 动态墙投影:status IN (2,3) 且严格脱敏(区/学段/科目/状态/时间)
-- 关联:t_demand / t_application / t_evaluation 1 ── 0..2
-- ============================================================
CREATE TABLE t_order (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, -- 主键,自增
    demand_id          BIGINT    NOT NULL,                              -- 关联需求(关联 t_demand.id)
    application_id     BIGINT    NOT NULL,                              -- 来源申请(关联 t_application.id)
    parent_user_id     BIGINT    NOT NULL,                              -- 家长(关联 t_user.id)
    tutor_user_id      BIGINT    NOT NULL,                              -- 老师(关联 t_user.id)
    status             SMALLINT  NOT NULL DEFAULT 0,                    -- 状态:0 待确认 / 1 待收费 / 2 试课中 / 3 已完成 / 4 试课失败 / 5 已取消
    fee_status         SMALLINT  NOT NULL DEFAULT 0,                    -- 信息费状态:0 未收 / 1 已收 / 2 已退(状态 4 强制为 2)
    fee_collected_at   TIMESTAMP,                                       -- 收费时间(→试课中,线下微信收取 99 元)
    fee_refunded_at    TIMESTAMP,                                       -- 退费时间(试课失败/收费后取消)
    fail_blame         SMALLINT,                                        -- 失败责任方:1 老师问题 / 2 家长问题(客服沟通后填写,审计追溯用)
    fail_reason        VARCHAR(255),                                    -- 试课失败原因(客服填)
    cancel_reason      VARCHAR(255),                                    -- 取消原因(老师反悔/家长放弃,客服填)
    tutor_confirmed_at TIMESTAMP,                                       -- 老师确认时间(→待收费)
    finished_at        TIMESTAMP,                                       -- 完成时间(客服标记)
    created_at         TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,    -- 订单生成时间(家长选中)
    updated_at         TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP     -- 更新时间
);
CREATE INDEX idx_t_order_tutor  ON t_order (tutor_user_id, status);     -- 老师端我的订单
CREATE INDEX idx_t_order_parent ON t_order (parent_user_id, status);    -- 家长端我的订单
CREATE INDEX idx_t_order_feed   ON t_order (status, updated_at);        -- 动态墙投影(status IN 2,3 按时间倒序)

COMMENT ON TABLE  t_order            IS '订单表(信息费前置;动态墙数据源,只读投影)';
COMMENT ON COLUMN t_order.demand_id        IS '关联需求(关联 t_demand.id)';
COMMENT ON COLUMN t_order.application_id   IS '来源申请(关联 t_application.id)';
COMMENT ON COLUMN t_order.parent_user_id   IS '家长(关联 t_user.id)';
COMMENT ON COLUMN t_order.tutor_user_id    IS '老师(关联 t_user.id)';
COMMENT ON COLUMN t_order.status           IS '状态:0 待确认(家长已选,等老师确认)/ 1 待收费(老师已确认,双方加客服微信)/ 2 试课中(已收费已发联系方式)/ 3 已完成 / 4 试课失败(已退费)/ 5 已取消';
COMMENT ON COLUMN t_order.fee_status       IS '信息费状态:0 未收 / 1 已收 / 2 已退;状态 4 必须为 2(退费后才能标记失败)';
